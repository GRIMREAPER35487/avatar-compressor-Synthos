using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Synthos.TextureAnalysis;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;
using VRC.SDK3.Avatars.Components;
using Object = UnityEngine.Object;

namespace dev.limitex.avatar.compressor.editor.texture
{
    /// <summary>
    /// Persists objects generated during an avatar build into a per-build temp folder and
    /// decides which existing assets the build may edit in place.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The VRChat SDK saves the processed avatar as a prefab before building the asset bundle,
    /// so every generated object it references (compressed textures, cloned materials, copied
    /// clips and controllers) must exist as an asset or the reference is dropped.
    /// </para>
    /// <para>
    /// Build folders are not deleted right after a build: VRCFury's Play Mode and
    /// "Build an Editor Test Copy" also run the build hooks and keep using the result. Instead,
    /// folders that no loaded avatar still references are removed before the next build,
    /// when entering Edit Mode and when the editor loads.
    /// </para>
    /// </remarks>
    internal sealed class BuildAssetStore
    {
        internal const string RootFolder = "Assets/_AvatarCompressorTemp";

        /// <summary>
        /// VRCFury writes each build's generated controllers here. Other folders in its temp
        /// package (SPS, PlayModeSettings, XR) persist across builds and are never edited.
        /// </summary>
        private const string VrcfuryBuildsFolder = "Packages/com.vrcfury.temp/Builds/";

        private readonly HashSet<string> _usedPaths = new HashSet<string>(
            StringComparer.OrdinalIgnoreCase
        );

        /// <summary>
        /// The folder this build writes into.
        /// </summary>
        public string Folder { get; }

        public BuildAssetStore(string avatarName)
        {
            EnsureFolder(RootFolder);
            Folder = AssetDatabase.GenerateUniqueAssetPath(
                $"{RootFolder}/{SanitizeName(avatarName, 24)}"
            );
            EnsureFolder(Folder);
        }

        /// <summary>
        /// Returns true if the object is safe to edit in place: it is not an asset, it was
        /// generated by this build, or it is a build copy generated by VRCFury.
        /// Files from earlier builds are not owned: a test copy may still use them.
        /// </summary>
        public bool IsBuildOwned(Object obj)
        {
            if (obj == null)
                return false;

            string path = AssetDatabase.GetAssetPath(obj);
            if (string.IsNullOrEmpty(path))
                return !IsUnsaveable(obj);

            return path.StartsWith(Folder + "/", StringComparison.OrdinalIgnoreCase)
                || path.StartsWith(VrcfuryBuildsFolder, StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// Saves a generated object into the build folder if it is not already an asset.
        /// </summary>
        public void Persist(Object obj)
        {
            if (obj == null || EditorUtility.IsPersistent(obj) || IsUnsaveable(obj))
                return;

            AssetDatabase.CreateAsset(obj, NextPath(obj.name, GetExtension(obj)));
        }

        /// <summary>
        /// Copies a main asset (including its embedded sub-assets, e.g. the state machines of an
        /// animator controller) into the build folder and returns the copy.
        /// Returns <c>null</c> if the asset cannot be copied.
        /// </summary>
        public T CopyAsset<T>(T asset)
            where T : Object
        {
            string sourcePath = AssetDatabase.GetAssetPath(asset);
            if (string.IsNullOrEmpty(sourcePath) || !AssetDatabase.IsMainAsset(asset))
                return null;

            string targetPath = NextPath(asset.name, Path.GetExtension(sourcePath));
            if (!AssetDatabase.CopyAsset(sourcePath, targetPath))
                return null;

            return AssetDatabase.LoadAssetAtPath<T>(targetPath);
        }

        /// <summary>
        /// Deletes build folders that no loaded avatar references anymore.
        /// Does nothing while in Play Mode.
        /// </summary>
        public static void CleanupUnused()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode)
                return;
            if (!AssetDatabase.IsValidFolder(RootFolder))
                return;

            var used = FindUsedBuildFolders();
            var stale = AssetDatabase
                .GetSubFolders(RootFolder)
                .Where(folder => !used.Contains(folder))
                .ToList();

            foreach (var folder in stale)
                AssetDatabase.DeleteAsset(folder);

            if (AssetDatabase.GetSubFolders(RootFolder).Length == 0)
                AssetDatabase.DeleteAsset(RootFolder);
        }

        private static HashSet<string> FindUsedBuildFolders()
        {
            var used = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            void Mark(Object obj)
            {
                if (obj == null)
                    return;
                string path = AssetDatabase.GetAssetPath(obj);
                if (!path.StartsWith(RootFolder + "/", StringComparison.OrdinalIgnoreCase))
                    return;
                int end = path.IndexOf('/', RootFolder.Length + 1);
                used.Add(end < 0 ? path : path.Substring(0, end));
            }

            foreach (var renderer in Object.FindObjectsOfType<Renderer>(true))
            {
                foreach (var material in renderer.sharedMaterials)
                    Mark(material);
            }

            foreach (var animator in Object.FindObjectsOfType<Animator>(true))
                Mark(animator.runtimeAnimatorController);

            foreach (var descriptor in Object.FindObjectsOfType<VRCAvatarDescriptor>(true))
            {
                foreach (
                    var layer in descriptor.baseAnimationLayers
                        ?? Array.Empty<VRCAvatarDescriptor.CustomAnimLayer>()
                )
                    Mark(layer.animatorController);
                foreach (
                    var layer in descriptor.specialAnimationLayers
                        ?? Array.Empty<VRCAvatarDescriptor.CustomAnimLayer>()
                )
                    Mark(layer.animatorController);
            }

            return used;
        }

        /// <summary>
        /// Editor-internal objects (e.g. <see cref="Texture2D.whiteTexture"/>) must never be
        /// moved into the build folder: deleting the folder later would destroy them.
        /// </summary>
        private static bool IsUnsaveable(Object obj)
        {
            return (obj.hideFlags & HideFlags.DontSaveInEditor) != 0;
        }

        private string NextPath(string name, string extension)
        {
            string baseName = SanitizeName(name, 48);
            string path = $"{Folder}/{baseName}{extension}";
            for (int i = 1; _usedPaths.Contains(path) || File.Exists(path); i++)
                path = $"{Folder}/{baseName}_{i}{extension}";

            _usedPaths.Add(path);
            return path;
        }

        private static string GetExtension(Object obj)
        {
            switch (obj)
            {
                case Material _:
                    return ".mat";
                case AnimationClip _:
                    return ".anim";
                case AnimatorController _:
                    return ".controller";
                case AnimatorOverrideController _:
                    return ".overrideController";
                default:
                    return ".asset";
            }
        }

        private static string SanitizeName(string name, int maxLength)
        {
            if (string.IsNullOrWhiteSpace(name))
                return "Asset";

            var invalid = Path.GetInvalidFileNameChars();
            var chars = name.Trim()
                .Select(c => invalid.Contains(c) || c == '.' ? '_' : c)
                .ToArray();
            string result = new string(chars);
            return result.Length > maxLength ? result.Substring(0, maxLength) : result;
        }

        private static void EnsureFolder(string path)
        {
            if (AssetDatabase.IsValidFolder(path))
                return;

            string parent = Path.GetDirectoryName(path)?.Replace('\\', '/');
            if (!string.IsNullOrEmpty(parent))
                EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, Path.GetFileName(path));
        }
    }

    /// <summary>
    /// Removes stale build folders when the editor loads and when leaving Play Mode.
    /// </summary>
    [InitializeOnLoad]
    internal static class BuildAssetStoreCleanup
    {
        static BuildAssetStoreCleanup()
        {
            EditorApplication.delayCall += BuildAssetStore.CleanupUnused;
            EditorApplication.playModeStateChanged += state =>
            {
                if (state == PlayModeStateChange.EnteredEditMode)
                    EditorApplication.delayCall += BuildAssetStore.CleanupUnused;
            };
        }
    }
}
